def fmt(text_id: str, **values) -> str:
    """Подставить {имя} в текст из GEN_TEXTS или TK_TEXTS; неизвестное имя остаётся как есть."""
    template = GEN_TEXTS.get(text_id)
    if template is None:
        template = TK_TEXTS[text_id]
    return re.sub(r"\{(\w+)\}", lambda m: str(values[m.group(1)]) if m.group(1) in values else m.group(0), template)


