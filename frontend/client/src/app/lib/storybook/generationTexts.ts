export type GenTextId = keyof typeof GEN_TEXTS;

export const gfmt = (id: GenTextId, vars: Record<string, string | number> = {}): string =>
  GEN_TEXTS[id].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));

