def build_adaptive_query_completeness_prompt(
    text: str,
    initial_response: Any,
    *,
    context_documents: tuple[str, ...] = (),
    schema_context: str = "",
) -> str:
    """Prompt for one mandatory correction of an initially valid QuerySpec."""
    escaped_initial_response = json.dumps(initial_response, ensure_ascii=False)
    escaped_schema_context = json.dumps(schema_context, ensure_ascii=False)
    schema_guidance = (
        "Используй доверенное ограниченное описание схемы только чтобы отличить "
        "описание домена или типа всех записей от условия отбора части строк; "
        "не добавляй таблицы, колонки или bindings в ответ. Если описание таблицы "
        "говорит, что все её записи относятся к названному домену или типу события, "
        "та же фраза внутри METRIC не является отдельным FILTER без самостоятельного "
        "условия отбора. "
        "Если доверенное описание схемы прямо подтверждает, что вся запрошенная "
        "составная фраза является одним готовым атрибутом, сохрани её одним "
        "semantic item подходящего вида: идентификатор или описательный атрибут "
        "остаётся DIMENSION, а числовой показатель — METRIC. Модификаторы внутри "
        "такого подтверждённого имени не создают отдельные ORDERING, METRIC или "
        "LIMIT; обычный запрос выбрать строку по экстремуму сохраняет эти элементы.\n\n"
        "Доверенное ограниченное описание схемы как JSON string:\n"
        f"{escaped_schema_context}\n\n"
        if schema_context
        else ""
    )
    return (
        build_adaptive_query_understanding_prompt(
            text,
            context_documents=context_documents,
        )
        + "\n\nПроверь первоначальный JSON-разбор. Верни исправленный полный "
        "JSON-объект по тому же контракту, а не diff и не пояснение. Он обязан "
        "покрывать каждый явно запрошенный результат или выходное поле, "
        "показатель, условие, группировку, порядок и limit из исходного текста "
        "и контекстных документов. "
        "Если элемент первоначального JSON явно подтверждён исходным текстом "
        "или контекстным документом, не удаляй его при исправлении и не объединяй "
        "явные условия и формулы внутри описания METRIC: сохраняй их отдельными "
        "semantic items. "
        "Если доверенный контекст говорит, что отличительное представление значения "
        "встречается только у целевой сущности или подмножества, сохраняй это условие "
        "как обязательный FILTER, даже когда конкретный SQL-operator ещё неизвестен. "
        "До исследования схемы оставляй operator и literal_or_reference равными null, "
        "а exact_physical_predicate — false. "
        "Сохраняй явно указанного владельца "
        "запрошенного атрибута из исходного текста и первоначального JSON: "
        "контекст события или транзакции задаёт условия поиска сущности, но не "
        "меняет владельца выходного атрибута, если исходный текст явно не просит "
        "атрибут события или транзакции.\n\n"
        f"{schema_guidance}"
        f"Первоначальный JSON-разбор как JSON object:\n{escaped_initial_response}"
    )


